import { expect, test } from '@playwright/test'

test('DB Editor authors an asset through the persistent Assets menu', async ({ page }) => {
  test.setTimeout(120_000)
  await page.goto('/editor/')
  await page.getByRole('button', { name: 'New Project', exact: true }).click()
  await page.getByPlaceholder('Project name', { exact: true }).fill('Database Workshop')
  await page.getByRole('button', { name: 'Create Project', exact: true }).click()
  const addAsset = page.getByRole('button', { name: 'Add asset', exact: true })
  await addAsset.click()
  await page.getByRole('button', { name: 'New DB Asset', exact: true }).click()

  const editor = page.getByRole('dialog', { name: 'DB Editor' })
  const button = (name: string) => editor.getByRole('button', { name, exact: true })
  await editor.getByLabel('Asset name').fill('Inventory')
  await button('Add column').click()
  await button('Rename column field_1').click()
  await editor.getByLabel('Column name').fill('stats')
  await button('Apply').click()
  await button('Add row').click()
  await button('Edit row_1 / stats').click()
  await editor.getByLabel('row_1 / stats (JSON)').fill('{')
  await button('Apply').click()
  await expect(editor.getByRole('alert')).toContainText('valid JSON')
  await expect(button('Save changes')).toBeDisabled()
  await editor.getByLabel('row_1 / stats (JSON)').fill('{"price":20,"tags":["quest"]}')
  await button('Apply').click()
  await button('Save changes').click()
  await expect(addAsset).toBeVisible()
  await page.getByRole('button', { name: /Inventory.*DB Asset/ }).dblclick()
  await expect(button('Edit row_1 / stats')).toHaveText('{"price":20,"tags":["quest"]}')
  await button('Close dialog').click()

  await addAsset.click()
  await page.getByRole('button', { name: 'New Dialogue & Quest Graph', exact: true }).click()
  const dialogue = page.getByRole('dialog', { name: 'Dialogue & Quest Graph Editor' })
  await dialogue.getByLabel('Jump to dialogue node').selectOption('d-act-1')
  await dialogue.getByLabel('Action', { exact: true }).selectOption('setDbValue')
  await dialogue.getByLabel('Database', { exact: true }).selectOption({ label: 'Inventory' })
  await dialogue.getByLabel('Row ID', { exact: true }).fill('row_1')
  await dialogue.getByLabel('Field path', { exact: true }).fill('stats.price')
  await dialogue.getByLabel('Value (JSON)').fill('45')
  await dialogue.getByRole('button', { name: 'Save changes', exact: true }).click()
  await page.getByRole('button', { name: /NPC Dialogue.*dialogue/ }).dblclick()
  await dialogue.getByLabel('Jump to dialogue node').selectOption('d-act-1')
  await expect(dialogue.getByLabel('Value (JSON)')).toHaveValue('45')
})
