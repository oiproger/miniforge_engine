import { expect, test } from '@playwright/test'

test('edit a model from the library, inspect its geometry and reopen the saved edit', async ({ page }) => {
  const button = (name: string) => page.getByRole('button', { name, exact: true })
  await page.goto('/editor/')
  await button('Open example Key Vault').click()
  await page.getByTitle('Vault Gate.gltf · double-click to use or edit').click()
  await button('Edit model').click()
  await expect(button('Frame')).toBeEnabled()
  await button('Frame').click()
  const grid = page.locator('.mf-model-editor').getByRole('button', { name: 'Grid', exact: true })
  await grid.click()
  await expect(grid).toHaveAttribute('aria-pressed', 'false')
  const filter = page.getByRole('searchbox', { name: 'Filter mesh parts' })
  await filter.fill('no such mesh')
  await expect(page.getByText('No matching mesh parts')).toBeVisible()
  await filter.fill('')
  const roughness = page.getByRole('spinbutton', { name: /roughness/i }).first()
  await roughness.fill('0.31')
  await roughness.press('Enter')
  await button('Save changes').click()
  await button('Edit model').click()
  await expect(roughness).toHaveValue('0.31')
})
